package com.fretline.app;

import android.util.Log;
import com.getcapacitor.JSArray;
import com.getcapacitor.JSObject;
import com.getcapacitor.Plugin;
import com.getcapacitor.PluginCall;
import com.getcapacitor.PluginMethod;
import com.getcapacitor.annotation.CapacitorPlugin;
import java.util.Collections;
import java.util.List;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;
import org.schabi.newpipe.extractor.Image;
import org.schabi.newpipe.extractor.NewPipe;
import org.schabi.newpipe.extractor.ServiceList;
import org.schabi.newpipe.extractor.downloader.Request;
import org.schabi.newpipe.extractor.downloader.Response;
import org.schabi.newpipe.extractor.localization.ContentCountry;
import org.schabi.newpipe.extractor.localization.Localization;
import org.schabi.newpipe.extractor.stream.StreamInfo;
import org.schabi.newpipe.extractor.stream.StreamSegment;
import org.schabi.newpipe.extractor.stream.SubtitlesStream;

/**
 * Lesson details from YouTube, the way NewPipe reads them (no API key):
 * title, channel, length, chapters and caption tracks; and the captions'
 * text. The video itself plays in YouTube's own player in the app.
 */
@CapacitorPlugin(name = "LessonInfo")
public class LessonInfoPlugin extends Plugin {

    private static final String TAG = "FretlineLesson";
    private static boolean initialized;
    private final ExecutorService executor = Executors.newFixedThreadPool(2);

    private static synchronized void init() {
        if (!initialized) {
            NewPipe.init(NpDownloader.get(), new Localization("en", "IN"), new ContentCountry("IN"));
            initialized = true;
        }
    }

    @PluginMethod
    public void info(PluginCall call) {
        String videoId = call.getString("videoId");
        if (videoId == null || videoId.isEmpty()) {
            call.reject("No video id");
            return;
        }
        executor.execute(() -> {
            try {
                init();
                StreamInfo info = StreamInfo.getInfo(ServiceList.YouTube, "https://www.youtube.com/watch?v=" + videoId);
                JSObject out = new JSObject();
                out.put("videoId", videoId);
                out.put("title", info.getName());
                out.put("uploader", info.getUploaderName());
                out.put("durationSec", info.getDuration());
                out.put("thumbnail", bestThumbnail(info.getThumbnails()));

                JSArray chapters = new JSArray();
                List<StreamSegment> segments = info.getStreamSegments();
                if (segments != null) {
                    for (StreamSegment s : segments) {
                        JSObject c = new JSObject();
                        c.put("title", s.getTitle());
                        c.put("startSec", s.getStartTimeSeconds());
                        chapters.put(c);
                    }
                }
                out.put("chapters", chapters);

                JSArray captions = new JSArray();
                List<SubtitlesStream> subs = info.getSubtitles();
                for (SubtitlesStream s : subs != null ? subs : Collections.<SubtitlesStream>emptyList()) {
                    if (!s.isUrl()) continue;
                    JSObject c = new JSObject();
                    c.put("lang", s.getLanguageTag());
                    c.put("name", s.getDisplayLanguageName());
                    c.put("auto", s.isAutoGenerated());
                    // Without its format, so the app can ask for the one it reads.
                    c.put("url", s.getContent().replaceAll("&fmt=[^&]*", ""));
                    captions.put(c);
                }
                out.put("captions", captions);
                call.resolve(out);
            } catch (Exception e) {
                Log.w(TAG, "info " + videoId, e);
                call.reject(describe(e));
            }
        });
    }

    /** Fetch a caption track (or any small YouTube text) and return it as text. */
    @PluginMethod
    public void fetchText(PluginCall call) {
        String url = call.getString("url");
        if (url == null || !url.startsWith("https://www.youtube.com/")) {
            call.reject("Not a YouTube address");
            return;
        }
        executor.execute(() -> {
            try {
                init();
                Response r = NpDownloader.get().execute(Request.newBuilder().get(url).build());
                if (r.responseCode() >= 400) throw new java.io.IOException("HTTP " + r.responseCode());
                JSObject out = new JSObject();
                out.put("text", r.responseBody() != null ? r.responseBody() : "");
                call.resolve(out);
            } catch (Exception e) {
                Log.w(TAG, "fetchText", e);
                call.reject(describe(e));
            }
        });
    }

    private static String bestThumbnail(List<Image> images) {
        String best = null;
        int bestHeight = -1;
        if (images == null) return null;
        for (Image image : images) {
            if (image.getHeight() > bestHeight) {
                bestHeight = image.getHeight();
                best = image.getUrl();
            }
        }
        return best;
    }

    private static String describe(Throwable e) {
        String msg = e.getMessage();
        return e.getClass().getSimpleName() + (msg != null ? ": " + msg : "");
    }
}
